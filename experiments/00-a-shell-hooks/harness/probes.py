def probe_ps0_subshell():
    """Q: do assignments inside PS0 persist into PROMPT_COMMAND?"""
    p = Pty("bash", fdsink=True)
    out = []
    p.send("PROMPT_COMMAND='printf \"result=[%s]\\n\" \"$_LI_T\" >&3; unset _LI_T'", 0.5)
    cases = [
        ("$( ) command substitution",
         "PS0='$( _LI_T=via_subst )'"),
        ("${v:=word} plain expansion",
         "PS0='${_LI_T:=via_default}'"),
        ("assignment inside arithmetic subscript",
         "PS0='${_LI_D[$((_LI_T:=via_subscript))]}'"),
    ]
    for name, code in cases:
        p.send("unset _LI_T", 0.3)
        p.send(code, 0.4)
        t = clean(p.send("echo MARKER-" + name.split()[0], 0.6))
        out.append("=== %s ===" % name)
        out.append("code: " + code)
        out.append("terminal tail: " + t[-160:].replace("\n", " | "))
    p.close()
    log("bash-ps0-subshell",
        ["Q: PS0 runs in a subshell; which assignment forms survive to the",
         "   PROMPT_COMMAND that follows?", ""] + out +
        ["", "--- FD 3 events ---"] + p.ev +
        ["", "CONCLUSION: $( ) and ${v:=...} do NOT persist (the expansion runs in a",
         "subshell); an assignment performed inside an arithmetic subscript DOES,",
         "and produces an empty string so the prompt stays clean. PS0 can therefore",
         "carry a free start tick, but not a start *event*."])


