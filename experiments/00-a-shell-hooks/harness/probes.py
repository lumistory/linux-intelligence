def probe_ps0_vs_promptcommand():
    """Q: what does PS0 see versus PROMPT_COMMAND, and when?"""
    p = Pty("bash", fdsink=True)
    out = []
    p.send("PS0='[PS0 rc=$? cmd={$BASH_COMMAND}]\\n'", 0.5)
    p.send("PROMPT_COMMAND='printf \"PC rc=%s hist=[%s]\\n\" \"$?\" \"$(HISTTIMEFORMAT= history 1)\" >&3'", 0.5)
    for c in ["echo one", "false", "echo two"]:
        out.append("=== typed: %s ===" % c)
        out.append(clean(p.send(c, 0.6)))
    p.close()
    log("bash-ps0-vs-promptcommand",
        ["Q: PS0 expands before the command; which status/command does it see?",
         "", "--- terminal ---"] + out +
        ["", "--- FD 3 events ---"] + p.ev +
        ["", "CONCLUSION: PS0 lags exactly one command (its rc/cmd belong to the",
         "previous line); PROMPT_COMMAND carries the true status of the line that",
         "just ran, and `history 1` carries that line's full text."])


