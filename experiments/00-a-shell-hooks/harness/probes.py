def probe_trap_pipe_inherit():
    """Q: does trap '' PIPE leak into children?"""
    pr = Pty("bash")
    a = clean(pr.send("grep -E \"^SigIgn\" /proc/self/status", 0.6))
    pr.close()
    pr = Pty("bash")
    b = clean(pr.send("trap '' PIPE; grep -E \"^SigIgn\" /proc/self/status", 0.6))
    pr.close()
    pr = Pty("bash")
    c = clean(pr.send("trap '' PIPE; ( grep -E \"^SigIgn\" /proc/self/status )", 0.6))
    pr.close()

    def sig(block):
        for ln in block.splitlines():
            if "SigIgn" in ln:
                parts = ln.replace("\t", " ").split()
                if len(parts) >= 2 and parts[0] == "SigIgn":
                    return parts[1]
                # terminal wrapped the line: value may sit on its own line
                for x in parts:
                    if x.startswith("0000"):
                        return x
        return "?"
    log("bash-trap-pipe-inherit", [
        "Q: does `trap '' PIPE` leak into commands the user runs?",
        "",
        "SigIgn bit 0x1000 is signal 13 (SIGPIPE).",
        "  baseline                 : 0x%s" % sig(a),
        "  after trap '' PIPE       : 0x%s" % sig(b),
        "  inside ( subshell )      : 0x%s" % sig(c),
        "",
        "CONCLUSION: yes, it is inherited by children and grandchildren, so a user",
        "command that ignores SIGPIPE itself would silently behave differently.",
        "This is why the adapter installs the trap only around its own write and",
        "restores the default immediately afterwards."])


