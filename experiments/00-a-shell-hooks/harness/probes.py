def probe_debug_trap():
    """Q: why is the DEBUG trap unsuitable as the event source?"""
    p = Pty("bash", fdsink=True)
    out = []
    p.send("trap 'printf \"DEBUG cmd=[%s] rc=%s\\n\" \"$BASH_COMMAND\" \"$?\" >&3' DEBUG", 0.5)
    for c in ["echo one",
              "printf 'a\\n' | wc -l",
              "true && echo chained",
              "echo A; echo B; echo C",
              "for i in 1 2 3; do echo L$i; done",
              "( echo S1; echo S2 )",
              "f() { echo in-f; }; f",
              "set -T; g() { echo in-g; }; g; set +T",
              "echo x=$(echo sub)"]:
        out.append("=== typed: %s ===" % c)
        before = len(p.ev)
        t = clean(p.send(c, 0.7))
        fired = [e for e in p.ev[before:]]
        out.append("DEBUG fired %d time(s):" % len(fired))
        for e in fired:
            out.append("   " + e[:120])
    # effect on xtrace
    before = len(p.ev)
    t = clean(p.send("set -x; echo traced; set +x", 0.7))
    out.append("=== with `set -x` ===")
    out.append(clean(t)[-400:])
    out.append("DEBUG fired %d time(s) during xtrace" % (len(p.ev) - before))
    p.close()
    log("bash-debugtrap", [
        "Q: is the DEBUG trap a usable CommandStarted/Finished source?",
        "",
        "For each typed line the probe counts how many DEBUG firings occur.",
        ""] + out + [
        "",
        "CONCLUSION: REJECTED.",
        "  1. It fires once per *simple* command, not per command line: a pipeline",
        "     or an && chain or a function call yields several events for one line,",
        "     and a shell loop yields one per iteration (6 for the 3-iteration",
        "     loop above). There is no way to tell",
        "     which firings belong to one user command without extra state.",
        "  2. It fires inside subshells, and inside function bodies as soon as",
        "     `set -T` (functrace) is in effect, so event counts depend on whether",
        "     runs -- the source becomes noisy exactly when commands are complex.",
        "  3. It is not run inside $( ) at all, so command substitutions are",
        "     invisible, while the enclosing line is visible: counts do not match.",
        "  4. Combined with `set -x` the two mechanisms interleave and both the",
        "     trace and the event stream become unreadable.",
        "PROMPT_COMMAND + `history 1` fires exactly once per typed line and carries",
        "the real status, so it wins on correctness and on cost."])


