def log(name, lines):
    os.makedirs(RES, exist_ok=True)
    path = os.path.join(RES, "probe-%s.log" % name)
    with open(path, "w") as f:
        f.write("# %s  (generated by harness/probes.py)\n" % name)
        for ln in lines:
            f.write(ln.rstrip("\n") + "\n")
    print("wrote", path)


class Pty:
    """Minimal pty session: send lines, collect terminal bytes, optional FD 3."""

    def __init__(self, shell, fdsink=False):
        import pty
        self.fdsink = fdsink
        if fdsink:
            self.ev_r, ev_w = os.pipe()
        pid, fd = pty.fork()
        if pid == 0:
            try:
                signal.signal(signal.SIGPIPE, signal.SIG_DFL)   # see drive.py
                signal.signal(signal.SIGXFSZ, signal.SIG_DFL)
                if fdsink:
                    tmp_r = self.ev_r
                    if tmp_r == 3:
                        tmp_r = os.dup(3)
                    os.dup2(ev_w, 3)
                    os.set_inheritable(3, True)
                    if ev_w != 3:
                        os.close(ev_w)
                    os.close(tmp_r)
                env = dict(os.environ)
                env.update({"TERM": "dumb" if shell == "fish" else "xterm-256color",
                            "PS1": PROMPT + " ", "PROMPT": PROMPT + " ",
                            "HISTFILE": os.devnull, "LC_ALL": "C.UTF-8"})
                if shell == "bash":
                    a = ["/usr/bin/bash", "--noprofile", "--rcfile", "/tmp/li-phase0-a/rc/bashrc", "-i"]
                elif shell == "zsh":
                    a = [ZSH, "-f", "-i"]
                else:
                    a = ["/usr/bin/fish", "--no-config", "-i", "-C",
                         "function fish_prompt; printf '%s ' " + PROMPT + "; end"]
                os.execvpe(a[0], a, env)
            except BaseException:
                os._exit(111)
        self.pid, self.fd = pid, fd
        os.set_blocking(fd, False)
        if fdsink:
            os.close(ev_w)
            self.evfd = self.ev_r
            os.set_blocking(self.evfd, False)
        self.buf = bytearray()
        self.ev = []
        self._drain(1.2)

    def _drain(self, t):
        end = time.monotonic() + t
        fds = [self.fd] + ([self.evfd] if self.fdsink else [])
        while time.monotonic() < end:
            try:
                r, _, _ = select.select(fds, [], [], 0.05)
            except (OSError, ValueError):
                return
            for f in r:
                try:
                    d = os.read(f, 262144)
                except OSError:
                    d = b""
                if f == self.fd:
                    self.buf.extend(d)
                else:
                    for line in d.split(b"\n"):
                        if line.strip():
                            self.ev.append(line.decode("utf8", "replace"))
        return bytes(self.buf)

    def send(self, line, wait=0.6):
        """Type one line; return only the bytes produced by this interaction."""
        self.buf.clear()
        try:
            os.write(self.fd, line.encode() + b"\r")
        except OSError:
            pass
        return self._drain(wait).decode("utf8", "replace")

    def raw(self, data, wait=0.6):
        self.buf.clear()
        try:
            os.write(self.fd, data)
        except OSError:
            pass
        return self._drain(wait).decode("utf8", "replace")

    def close(self):
        alive = True
        try:
            d, st = os.waitpid(self.pid, os.WNOHANG)
            alive = (d == 0)
        except ChildProcessError:
            alive = False
            st = 0
        if alive:
            try:
                os.kill(self.pid, 9)
                os.waitpid(self.pid, 0)
            except OSError:
                pass
        self._drain(0.2)
        for f in ([self.fd] + ([self.evfd] if self.fdsink else [])):
            try:
                os.close(f)
            except OSError:
                pass
        return alive, st


def clean(s):
    import re
    s = re.sub(r"\x1b\[[?0-9;]*[a-zA-Z]", "", s)
    s = re.sub(r"\x1b\][^\x07]*\x07", "", s)
    s = s.replace("\r", "")
    return "\n".join(l.rstrip() for l in s.splitlines() if l.strip())


