def probe_fish_term():
    """Q: does fish work in a bare pty, and under which TERM?"""
    rows = []
    for term in ["xterm-256color", "dumb"]:
        os.environ["TERM"] = term
        p = Pty("fish")
        got = p.buf.decode("utf8", "replace")
        out = clean(p.send("echo fish-alive", 1.0))
        rows.append("TERM=%-14s startup_bytes=%4d  prompt_seen=%-5s  "
                    "command_worked=%s" %
                    (term, len(got), PROMPT in got, "fish-alive" in out))
        p.close()
    log("fish-term", [
        "Q: fish 4.9.3 in a bare pty -- does it reach a prompt?",
        "",
        "fish queries the terminal (DA1, OSC11, keyboard protocol) at startup and",
        "waits for replies a bare pty never sends.",
        ""] + rows + [
        "",
        "CONCLUSION: with a real TERM value fish blocks on capability queries and",
        "never paints a prompt; TERM=dumb skips the queries and everything works.",
        "This is a harness constraint, not a fish hook limitation."])


