def probe_dead_pipe():
    """Q: what happens when the hook writes to a pipe whose reader is gone?"""
    rows = []

    def trial(label, probe):
        p = Pty("bash")
        p.send("exec 3> >(true); sleep 0.4", 1.1)      # reader exits at once
        out = clean(p.send(probe + '; echo "rc=$?"', 1.2))
        after = clean(p.send("echo STILL-ALIVE", 1.0))
        alive, st = p.close()
        rows.append("%-34s shell_survived=%-5s SIGPIPE_died=%-5s output=%r"
                    % (label, alive, (not alive) and os.WIFSIGNALED(st),
                       after.strip()[:40]))

    trial("raw write to dead pipe", 'printf "p\\n" >&3 2>/dev/null')
    trial("write inside trap '' PIPE",
          'trap "" PIPE; printf "p\\n" >&3 2>/dev/null; trap - PIPE')
    trial("write from a subshell",
          '( printf "p\\n" >&3 ) 2>/dev/null')
    trial("python connect to dead socket",
          "python3 -c 'import socket;s=socket.socket(socket.AF_UNIX);"
          "s.connect(\"%s/dead.sock\")' 2>/dev/null" % TMP)
    log("bash-sigpipe", [
        "Q: a hook writes to a sink that died. Does the shell survive?",
        "",
        "Setup: FD 3 is a process-substitution pipe whose reader (`true`) exits",
        "immediately, so every later write hits a closed pipe.",
        ""] + rows + [
        "",
        "CONCLUSION: a raw write to a dead pipe KILLS the interactive shell -- the",
        "hook must never trust the sink. `trap '' PIPE` around the write, writing",
        "from a subshell, or a connect() that fails cleanly all survive. A daemon",
        "that has gone away must never be able to take the user's shell with it."])


