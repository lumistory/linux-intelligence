def _count(path):
    try:
        return open(path).read().count("hit")
    except OSError:
        return 0


def probe_ps0_count():
    """Q: does PS0 fire exactly once per typed line, and not for blank lines?"""
    p = Pty("bash")
    p.send("PS0='$(echo hit >> %s/ps0cnt)'" % TMP, 0.5)
    counts = []
    for label, seq in [("one normal command", ["echo a"]),
                       ("two commands", ["echo b", "echo c"]),
                       ("blank line then command", ["", "echo d"]),
                       ("pipeline", ["true | cat"]),
                       ("for loop", ["for i in 1 2 3; do echo $i; done"])]:
        base = _count(TMP + "/ps0cnt")
        for c in seq:
            p.send(c, 0.5)
        p.send("", 0.3)
        n = _count(TMP + "/ps0cnt") - base
        counts.append("%-26s typed_lines=%-2d PS0_fires=%d"
                      % (label, len(seq), n))
    p.close()
    log("bash-ps0-count", [
        "Q: how many times does PS0 expand per interaction?",
        ""] + counts + [
        "",
        "CONCLUSION: exactly once per executed command line, zero times for a blank",
        "line (Enter on an empty prompt executes nothing, so PS0 never runs). That",
        "makes PS0 a dependable per-command hook *tick*, and it is why the adapter",
        "uses the PS0 counter to detect 'nothing ran' instead of comparing text."])


def main():
    os.makedirs(TMP, exist_ok=True)
    probes = [probe_ps0_vs_promptcommand, probe_ps0_subshell, probe_dead_pipe,
              probe_trap_pipe_inherit, probe_fork_cost, probe_zsh_overflow,
              probe_fish_term,
              probe_unix_socket_open, probe_debug_trap, probe_ps0_count]
    only = sys.argv[1:] or None
    for fn in probes:
        if only and fn.__name__ not in only:
            continue
        try:
            fn()
        except Exception as e:                       # keep going, report honestly
            print("PROBE FAILED %s: %r" % (fn.__name__, e), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
