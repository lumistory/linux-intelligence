def probe_unix_socket_open():
    """Q: can each shell open an AF_UNIX socket by redirection?"""
    import socket
    os.makedirs(TMP, exist_ok=True)
    path = os.path.join(TMP, "live.sock")
    try:
        os.unlink(path)
    except OSError:
        pass
    srv = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    srv.bind(path)
    srv.listen(8)
    srv.setblocking(False)
    rows = []
    for shell in ("bash", "zsh", "fish"):
        p = Pty(shell)
        out = clean(p.send("printf 'probe\\n' > %s; echo rc=$?" % path, 0.8))
        got = False
        for _ in range(20):
            try:
                c, _ = srv.accept()
                got = True
                c.close()
            except (BlockingIOError, InterruptedError):
                break
        rows.append("%-5s redirection_result=%r  daemon_received=%s"
                    % (shell, out.strip()[:90], got))
        p.close()
    # zsh's own socket builtin, if the module loads
    p = Pty("zsh")
    out = clean(p.send("module_path=(%s $module_path); zmodload zsh/net/socket; "
                       "echo modload_rc=$?; zsocket %s; echo zsocket_rc=$?"
                       % (ZMOD, path), 1.0))
    rows.append("zsh   zsocket attempt=%r" % out.strip()[:120])
    p.close()
    srv.close()
    log("unix-socket-open", [
        "Q: can a shell write to an AF_UNIX SOCK_STREAM socket by redirection?",
        "",
        "A live listening socket exists at %s." % path,
        ""] + rows + [
        "",
        "CONCLUSION: paths that are sockets cannot be opened with > : bash reports",
        "ENXIO (no such device or address), zsh and fish are no better. A shell",
        "hook therefore cannot dial the daemon; the FD must be inherited from the",
        "launcher, or an external helper must do the connect.",
        "zsh/net/socket is the only exception and it is an extra module that the",
        "unpacked zsh copy must load explicitly."])


