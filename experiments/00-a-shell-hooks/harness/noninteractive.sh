#!/usr/bin/env bash
# harness/noninteractive.sh -- negative control (README H-A6).
#
# A hook that fires in a script is worse than useless: it doubles the event
# stream for every command a script runs. These runs must produce ZERO events.
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(dirname "$HERE")
RES="$ROOT/results"
ADAPT="$ROOT/adapters"
ZSH=${LI_ZSH:-<WORKSPACE>/experiments/toolchain/root/usr/bin/zsh}
OUT="$RES/noninteractive.log"
: > "$OUT"

log() { printf '%s\n' "$*" >> "$OUT"; }

run_case() {   # $1=label $2=expected $3...=command
  local label=$1 ; shift
  local tmp="$RES/noninteractive-fd3.$$"
  local n
  : > "$tmp"
  ( exec 3>"$tmp" ; "$@" >/dev/null 2>&1 )
  n=$(wc -c < "$tmp")
  log "$(printf '%-46s fd3_bytes=%-4s verdict=%s' \
        "$label" "$n" "$([ "$n" -eq 0 ] && echo SILENT_as_required || echo HOOK_FIRED_in_noninteractive)")"
  : > "$tmp"
}

log "# noninteractive  (generated by harness/noninteractive.sh)"
log "# A hook must be completely silent outside an interactive shell."
log ""

# --- bash ---
run_case "bash -c  (sources adapter)"       "$BASH_VERSION" \
  bash --norc --noprofile -c ". $ADAPT/bash.sh; echo hi; false; echo bye"
run_case "bash script.sh"                   "script" \
  bash --norc --noprofile -c "printf '. $ADAPT/bash.sh\necho hi\nfalse\n' > /tmp/li-phase0-a/s.sh; bash --norc --noprofile /tmp/li-phase0-a/s.sh"
# `-i -c` is worth its own note: $- contains `i`, so the adapter believes it is
# interactive, but bash never runs PS0/PROMPT_COMMAND in `-c` mode, so no event
# is produced anyway. Verified separately with a real pty.
run_case "bash -i -c  (interactive forced)"  "forced" \
  bash --norc --noprofile -i -c ". $ADAPT/bash.sh; echo hi"

# --- zsh ---
run_case "zsh -f -c (sources adapter)"      "$ZSH" \
  "$ZSH" -f -c "source $ADAPT/zsh.zsh; echo hi; false; echo bye"
run_case "zsh -f script"                    "script" \
  "$ZSH" -f -c "printf 'source $ADAPT/zsh.zsh\necho hi\nfalse\n' > /tmp/li-phase0-a/s.zsh; $ZSH -f /tmp/li-phase0-a/s.zsh"
run_case "zsh -f -i -c (interactive forced)" "$ZSH" \
  "$ZSH" -f -i -c "source $ADAPT/zsh.zsh; echo hi"

# --- fish ---
run_case "fish -c (sources adapter)"        "fish" \
  fish --no-config -c "source $ADAPT/fish.fish; echo hi; false; echo bye"
run_case "fish script.fish"                 "script" \
  fish --no-config -c "printf 'source $ADAPT/fish.fish\necho hi\nfalse\n' > /tmp/li-phase0-a/s.fish; fish --no-config /tmp/li-phase0-a/s.fish"

log ""
log "EXPECTED: every line above reads SILENT_as_required."
log "fd3_bytes is the number of bytes the adapter wrote to its sink FD."
log "Note: the adapters install their hooks only when the shell reports"
log "itself interactive, so the non-interactive paths return before"
log "installing anything."
